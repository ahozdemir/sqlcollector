using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Data.SqlClient;

namespace SqlDataCollector.Infrastructure;

/// <param name="MetadataDb">Metadata database (etl.*, embedded Hangfire).</param>
/// <param name="DwhDb">Target database for collected data.</param>
/// <param name="ServiceAccount">Windows account the services run as (DOMAIN\user or DOMAIN\gmsa$); null = no logins/permissions.</param>
/// <param name="Central">Central (shared) Hangfire database instead of embedded.</param>
/// <param name="HangfireDb">Central mode: the Hangfire database.</param>
/// <param name="HangfireSchema">Hangfire schema name.</param>
public sealed record DbSetupOptions(string MetadataDb, string DwhDb, string? ServiceAccount, bool Central = false,
    string? HangfireDb = null, string HangfireSchema = "hangfire_collector")
{
    public void Validate()
    {
        foreach (var (name, value) in new[] { ("metadata database", MetadataDb), ("DWH database", DwhDb) })
            if (string.IsNullOrWhiteSpace(value) || value.Length > 128) throw new ArgumentException($"Invalid {name} name.");
        if (MetadataDb.Equals(DwhDb, StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("The metadata and DWH databases must be different.");
        if (ServiceAccount is not null && !Regex.IsMatch(ServiceAccount, @"^[^\\\s]+\\[^\\\s]+$"))
            throw new ArgumentException("The service account must be DOMAIN\\name.");
        if (Central && string.IsNullOrWhiteSpace(HangfireDb)) throw new ArgumentException("Central mode needs the Hangfire database name.");
    }
}

/// <summary>
/// Database setup used by the installer: the same SQL as files for a DBA ("later"/"manual") or executed directly with the
/// installing user's Windows account ("now"). Mirrors sql/01_permissions_template.sql for one service account running Web and Worker.
/// </summary>
public static partial class DbSetup
{
    public const string ExportReader = "sdc_export_reader";

    /// <summary>The setup scripts in execution order (file name, SQL with GO separators).</summary>
    public static IReadOnlyList<(string FileName, string Sql)> Scripts(DbSetupOptions o)
    {
        o.Validate();
        var list = new List<(string, string)>
        {
            ("01_databases_and_permissions.sql", DatabasesAndPermissions(o)),
            ("02_etl_schema.sql", $"USE {SqlIdent.Quote(o.MetadataDb)};\nGO\n{EtlSchemaScript()}")
        };
        if (o.Central) list.Add(("03_hangfire_central.sql", CentralHangfire(o)));
        return list;
    }

    public static string DatabasesAndPermissions(DbSetupOptions o)
    {
        var sb = new StringBuilder();
        sb.AppendLine("/* SqlDataCollector – databases and service account permissions (generated by the installer).");
        sb.AppendLine("   Run with a sysadmin (or dbcreator + securityadmin) account. Idempotent. */");
        sb.AppendLine("SET NOCOUNT ON;");
        sb.AppendLine($"IF DB_ID({Lit(o.MetadataDb)}) IS NULL CREATE DATABASE {SqlIdent.Quote(o.MetadataDb)};");
        sb.AppendLine($"IF DB_ID({Lit(o.DwhDb)}) IS NULL CREATE DATABASE {SqlIdent.Quote(o.DwhDb)};");
        sb.AppendLine("GO");

        var acc = o.ServiceAccount;
        if (acc is not null)
        {
            sb.AppendLine($"IF SUSER_ID({Lit(acc)}) IS NULL CREATE LOGIN {SqlIdent.Quote(acc)} FROM WINDOWS;");
            sb.AppendLine("GO");
        }

        // metadata DB: read/write + DDL (etl schema upgrades on new versions, embedded Hangfire schema)
        sb.AppendLine($"USE {SqlIdent.Quote(o.MetadataDb)};");
        if (acc is not null)
        {
            AddUser(sb, acc);
            foreach (var role in new[] { "db_datareader", "db_datawriter", "db_ddladmin" }) sb.AppendLine($"ALTER ROLE {role} ADD MEMBER {SqlIdent.Quote(acc)};");
        }
        sb.AppendLine("GO");

        // DWH: load + DDL + partitions, UI reads; read-only user for export reads (EXECUTE AS USER)
        sb.AppendLine($"USE {SqlIdent.Quote(o.DwhDb)};");
        sb.AppendLine($"IF DATABASE_PRINCIPAL_ID({Lit(ExportReader)}) IS NULL CREATE USER {SqlIdent.Quote(ExportReader)} WITHOUT LOGIN;");
        sb.AppendLine($"ALTER ROLE db_datareader ADD MEMBER {SqlIdent.Quote(ExportReader)};");
        if (acc is not null)
        {
            AddUser(sb, acc);
            foreach (var role in new[] { "db_datareader", "db_datawriter", "db_ddladmin" }) sb.AppendLine($"ALTER ROLE {role} ADD MEMBER {SqlIdent.Quote(acc)};");
            sb.AppendLine($"GRANT ALTER ANY DATASPACE TO {SqlIdent.Quote(acc)};");
            sb.AppendLine($"GRANT VIEW DEFINITION TO {SqlIdent.Quote(acc)};");
            sb.AppendLine($"GRANT IMPERSONATE ON USER::{SqlIdent.Quote(ExportReader)} TO {SqlIdent.Quote(acc)};");
        }
        sb.AppendLine("GO");
        sb.AppendLine("/* Sources: on every source database grant the service account read access only, e.g.");
        sb.AppendLine($"   USE [ERP]; CREATE USER {SqlIdent.Quote(acc ?? "DOMAIN\\svc")} FOR LOGIN {SqlIdent.Quote(acc ?? "DOMAIN\\svc")}; ALTER ROLE db_datareader ADD MEMBER {SqlIdent.Quote(acc ?? "DOMAIN\\svc")}; */");
        return sb.ToString();
    }

    public static string CentralHangfire(DbSetupOptions o)
    {
        var sb = new StringBuilder();
        sb.AppendLine("/* SqlDataCollector – own schema in the central Hangfire database. Run once by the DBA (db_owner). */");
        sb.AppendLine("SET ANSI_NULLS ON;\nSET QUOTED_IDENTIFIER ON;  -- sqlcmd defaults to OFF");
        sb.AppendLine("GO");
        sb.AppendLine($"USE {SqlIdent.Quote(o.HangfireDb!)};");
        sb.AppendLine("GO");
        sb.AppendLine(Hangfire.SqlServer.SqlServerObjectsInstaller.GetInstallScript(o.HangfireSchema, false));
        sb.AppendLine("GO");
        if (o.ServiceAccount is { } acc)
        {
            sb.AppendLine($"IF SUSER_ID({Lit(acc)}) IS NULL CREATE LOGIN {SqlIdent.Quote(acc)} FROM WINDOWS;");
            AddUser(sb, acc);
            sb.AppendLine($"GRANT SELECT, INSERT, UPDATE, DELETE ON SCHEMA::{SqlIdent.Quote(o.HangfireSchema)} TO {SqlIdent.Quote(acc)};");
            sb.AppendLine("GO");
        }
        return sb.ToString();
    }

    /// <summary>Runs scripts 01 and 02 with the given (sysadmin) connection; the central Hangfire script is left to the DBA.</summary>
    public static async Task InstallAsync(string masterConnectionString, DbSetupOptions o, Action<string>? log, CancellationToken ct)
    {
        o.Validate();
        await using var conn = new SqlConnection(new SqlConnectionStringBuilder(masterConnectionString) { InitialCatalog = "master" }.ConnectionString);
        await conn.OpenAsync(ct);
        foreach (var (file, sql) in Scripts(o).Where(s => !s.FileName.StartsWith("03", StringComparison.Ordinal)))
        {
            log?.Invoke($"Running {file} …");
            foreach (var batch in GoSeparator().Split(sql).Where(b => !string.IsNullOrWhiteSpace(b)))
            {
                await using var cmd = conn.CreateCommand();
                cmd.CommandText = batch;
                cmd.CommandTimeout = 600;
                await cmd.ExecuteNonQueryAsync(ct);
            }
        }
        log?.Invoke("Databases, etl schema and permissions are ready.");
    }

    private static void AddUser(StringBuilder sb, string acc) =>
        sb.AppendLine($"IF DATABASE_PRINCIPAL_ID({Lit(acc)}) IS NULL CREATE USER {SqlIdent.Quote(acc)} FOR LOGIN {SqlIdent.Quote(acc)};");

    private static string Lit(string s) => "N'" + s.Replace("'", "''") + "'";

    private static string EtlSchemaScript()
    {
        var asm = typeof(DbSetup).Assembly;
        var name = asm.GetManifestResourceNames().Single(n => n.EndsWith("001_schema.sql", StringComparison.OrdinalIgnoreCase));
        using var s = asm.GetManifestResourceStream(name)!;
        using var r = new StreamReader(s);
        return r.ReadToEnd();
    }

    [GeneratedRegex(@"^\s*GO\s*;?\s*$", RegexOptions.Multiline | RegexOptions.IgnoreCase)]
    private static partial Regex GoSeparator();
}
